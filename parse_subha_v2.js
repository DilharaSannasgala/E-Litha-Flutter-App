const lines = raw.split('\n').map(l => l.trim()).filter(l => l);

let currentMonthIndex = 0;
const monthsSinhala = [
    'ÿre;= - ckjdß',
    'kjï - fmnrjdß',
    'ueÈka - ud¾;=',
    'nla - wfm%a,a',
    'fjila - uehs',
    'fmdfidka - cQks',
    'wei< - cQ,s',
    'kslsKs - wf.daia;=',
    'ìkr - iema;eïn¾',
    'jma - Tlaf;dan¾',
    'b,a - fkdjeïn¾',
    'W|qjma - foieïn¾'
];

function formatTime(timeStr) {
    return timeStr.replace(/(\d{2})[.](\d{2})/g, (match, h, m) => {
        let hr = parseInt(h, 10);
        let min = m;
        let suffix = hr >= 12 ? 'wmrNd.' : 'mQ¾jNd.';
        let h12 = hr % 12;
        if (h12 === 0) h12 = 12;
        let pHR = h12.toString().padStart(2, '0');
        return `${suffix} ${pHR}-${min}`;
    });
}

let items = [];
for (let i = 0; i < lines.length; ) {
    if (lines[i].includes('·')) {
        currentMonthIndex++;
        i++;
    } else {
        const day = lines[i];
        let desc = lines[i+1];
        
        let descMapped = desc;
        if (desc.includes('න්පසු')) descMapped = descMapped.replace('න්පසු', 'ka miq');
        if (desc.includes('දක්වා')) descMapped = descMapped.replace('දක්වා', 'olajd');
        if (desc.includes('මුළු දවසම')) descMapped = descMapped.replace('මුළු දවසම', 'uq¿ ojiu');
        
        descMapped = formatTime(descMapped);
        
        items.push({
            monthId: currentMonthIndex,
            day: day,
            time: descMapped,
            timeOriginal: desc
        });
        i += 2;
    }
}

// Group by month
const grouped = [];
for(let m=1; m<=12; m++) {
    grouped.push({
        id: m,
        monthName: monthsSinhala[m-1],
        days: items.filter(x => x.monthId === m).map(x => ({day: x.day, time: x.time, timeOriginal: x.timeOriginal}))
    });
}

const data = {
    months: grouped
};

fs.writeFileSync('assets/data/subha_dawasa_data.json', JSON.stringify(data, null, 2));
